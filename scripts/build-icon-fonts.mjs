/**
 * Builds tiny Font Awesome / Bootstrap Icons fonts that contain ONLY the icons this
 * site uses (a few KB instead of ~400 KB from the CDNs). Same glyphs, same CSS rules,
 * so icons look exactly as before.
 *
 *   npm run icons      (run again after using a new fa-* or bi-* icon class)
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { PurgeCSS } from 'purgecss';
import subsetFont from 'subset-font';

const root = new URL('..', import.meta.url).pathname;
const nm = (p) => join(root, 'node_modules', p);

function sourceFiles(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? sourceFiles(p) : /\.(jsx?|html)$/.test(f) ? [p] : [];
  });
}
const source = sourceFiles(join(root, 'src')).map((f) => readFileSync(f, 'utf8')).join('\n');
const used = (prefix) => [...new Set(source.match(new RegExp(`\\b${prefix}-[a-z0-9-]+`, 'g')) || [])];

async function build({ name, css, fonts, classes, base }) {
  const [result] = await new PurgeCSS().purge({
    content: [{ raw: `<i class="${[...base, ...classes].join(' ')}"></i>`, extension: 'html' }],
    css: [{ raw: readFileSync(css, 'utf8') }],
    fontFace: true,
  });
  let out = result.css;
  const codepoints = [...out.matchAll(/content:\s*"\\([0-9a-f]+)"/gi)].map((m) => String.fromCodePoint(parseInt(m[1], 16)));
  for (const [family, file, target] of fonts) {
    const face = new RegExp(`@font-face\\s*{[^}]*font-family:\\s*["']?${family}["']?[^}]*}`, 'g');
    if (!face.test(out)) continue;
    const subset = await subsetFont(readFileSync(file), codepoints.join(''), { targetFormat: 'woff2' });
    writeFileSync(join(root, 'src/assets/fonts', target), subset);
    out = out.replace(face, (block) => block.replace(/src:[^;}]*/, `src:url("../../assets/fonts/${target}") format("woff2")`));
    console.log(`${target}: ${codepoints.length} glyphs, ${(subset.length / 1024).toFixed(1)} KB`);
  }
  writeFileSync(join(root, 'src/styles/vendor', name), `/* Generated by scripts/build-icon-fonts.mjs - do not edit */\n${out}\n`);
}

const fa = used('fa').filter((c) => !['fa-solid', 'fa-brands'].includes(c));
await build({
  name: 'fontawesome-subset.css',
  css: nm('@fortawesome/fontawesome-free/css/all.css'),
  base: ['fa', 'fas', 'fab', 'fa-solid', 'fa-brands'],
  classes: fa,
  fonts: [
    ['Font Awesome 6 Free', nm('@fortawesome/fontawesome-free/webfonts/fa-solid-900.woff2'), 'fa-solid-900.subset.woff2'],
    ['Font Awesome 6 Brands', nm('@fortawesome/fontawesome-free/webfonts/fa-brands-400.woff2'), 'fa-brands-400.subset.woff2'],
  ],
});
await build({
  name: 'bootstrap-icons-subset.css',
  css: nm('bootstrap-icons/font/bootstrap-icons.css'),
  base: ['bi'],
  classes: used('bi'),
  fonts: [['bootstrap-icons', nm('bootstrap-icons/font/fonts/bootstrap-icons.woff2'), 'bootstrap-icons.subset.woff2']],
});
console.log('icons:', fa.join(' '));
